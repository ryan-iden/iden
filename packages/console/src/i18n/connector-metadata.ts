const translations = new Map(
  connectorMetadataTranslations.map(([source, cn, tw]) => [source, { cn, tw }])
);

export const translateConnectorMetadata = (text: string | undefined, language: string) => {
  if (!text || !/^zh(?:-|$)/i.test(language)) {
    return text;
  }
  const entry = translations.get(text.trim());
  return entry ? (/^zh-(?:tw|hk|hant)(?:-|$)/i.test(language) ? entry.tw : entry.cn) : text;
};
